import { defineConfig, defineRule, type AgentlintNode } from '@aurelienbbn/agentlint';

/**
 * Rules from AGENTS.md. agentlint parses JavaScript, TypeScript and JSON only; the em dash rule for Astro,
 * Markdown, MDX, CSS, HTML, YAML and the other text files lives in tests/copy-rules.test.mjs (npm run test:unit).
 */

/** Leaf nodes that hold source text: comments, string pieces, escapes, JSX text and regex bodies. */
const TEXT_NODES = [
  'comment',
  'string_fragment',
  'string_content',
  'escape_sequence',
  'jsx_text',
  'html_character_reference',
  'regex_pattern',
] as const;

/** The character itself, its JS and JSON escapes, and its HTML entities. */
const EM_DASH = /—|\\u\{?2014\}?|&mdash;|&#8212;|&#x2014;/i;

const noEmDash = defineRule({
  lifecycle: 'state',
  standard: {
    id: 'copy/no-em-dash',
    revision: 1,
    title: 'No em dashes',
    guidance: {
      standard:
        'Text has no em dash (U+2014), written or escaped: UI copy, docs, comments, tests and data. Rewrite with a period, comma, colon or parentheses.',
      checks: ['There is no exception: rewrite the sentence instead of accepting the finding.'],
      examples: [
        { label: 'Period', code: "'Built in 2016. Still running.'" },
        { label: 'Colon', code: "'One rule: ship the work.'" },
      ],
      refs: [{ type: 'url', href: 'https://github.com/samu-el/personal-website/blob/master/AGENTS.md' }],
    },
    source: { type: 'file', path: 'AGENTS.md' },
  },
  detector: {
    id: 'text/em-dash',
    version: 1,
    scan: 'file',
    createOnce({ context }) {
      const visit = (node: AgentlintNode) => {
        if (EM_DASH.test(node.text))
          context.report({ node, message: 'Em dash: rewrite with a period, comma, colon or parentheses.' });
      };
      return Object.fromEntries(TEXT_NODES.map((type) => [type, visit]));
    },
    fixtures: {
      mustReport: [
        "const a = 'Built in 2016 — still running';",
        "const b = 'Built in 2016 \\u2014 still running';",
        'const c = `Built in ${year} \\u{2014} still running`;',
        '// One rule — ship the work',
        { file: 'fixture.tsx', source: 'const d = <p>One rule &mdash; ship it</p>;' },
        { file: 'fixture.tsx', source: 'const e = <p>One rule — ship it</p>;' },
        { file: 'fixture.json', source: '{ "title": "One rule \\u2014 ship it" }' },
      ],
      mustStaySilent: [
        "const a = 'Built in 2016. Still running.';",
        "const b = 'Pages 2–4, en dash ranges are fine';",
        "const c = 'a - b, hyphens are fine';",
        { file: 'fixture.json', source: '{ "occurredAt": 1792014662364 }' },
      ],
    },
  },
  binding: {
    id: 'copy/no-em-dash',
    authority: 'human',
    include: ['**/*.{ts,tsx,mts,cts,js,jsx,mjs,cjs,json}'],
    // The rule's own matchers must spell the character; package-lock.json is regenerated by npm.
    exclude: ['.agentlint/config.ts', 'tests/copy-rules.test.mjs', '**/package-lock.json'],
  },
});

/** Property names that carry a tagline, a helper line or a secondary label under a heading. */
const SECONDARY_TEXT_KEYS =
  /^(tagline|subtitle|subheading|subhead|eyebrow|kicker|lede|dek|helperText|helper|hint|caption|blurb|summary)$/;

const noSecondaryText = defineRule({
  lifecycle: 'state',
  standard: {
    id: 'copy/no-secondary-text',
    revision: 1,
    title: 'No taglines, helper text or secondary labels',
    guidance: {
      standard:
        'A screen makes sense from its headings, its content and its layout. Taglines, helper lines and secondary labels are cut; if a screen needs one, fix the layout.',
      checks: [
        'Delete the line when the heading or the content already says it.',
        'Text that is the content itself (a role description, a project write-up, a meta description for search) can stay: accept with a reason naming what it carries.',
      ],
      examples: [{ label: 'Heading and content only', code: "{ title: 'Stack', items }" }],
      refs: [{ type: 'url', href: 'https://github.com/samu-el/personal-website/blob/master/AGENTS.md' }],
    },
    source: { type: 'file', path: 'AGENTS.md' },
  },
  detector: {
    id: 'ts/secondary-text-property',
    version: 1,
    scan: 'file',
    createOnce({ context }) {
      return {
        pair(node: AgentlintNode) {
          const key = node.childByFieldName('key');
          const value = node.childByFieldName('value');
          if (!key || !value || !SECONDARY_TEXT_KEYS.test(key.text.replace(/^['"]|['"]$/g, ''))) return;
          if (value.type !== 'string' && value.type !== 'template_string') return;
          if (value.text.length <= 2) return;
          context.report({
            node,
            message: `"${key.text}" holds secondary text. Cut it, or say what content it carries.`,
          });
        },
      };
    },
    fixtures: {
      mustReport: [
        "const hero = { title: 'Work', tagline: 'Things I have built' };",
        'const field = { label: "Email", helperText: `We never share it` };',
      ],
      mustStaySilent: [
        "const hero = { title: 'Work', items: [] };",
        "const role = { summary: '' };",
        'const row = { hint: entry.handle };',
        "const meta = { description: 'Personal site of Samuel Mussie.' };",
      ],
    },
  },
  binding: {
    id: 'copy/no-secondary-text',
    authority: 'agent',
    include: ['src/**/*.{ts,tsx,js,mjs}'],
  },
});

/** A middle dot used as a separator: the character, its escape or its entity, with space on both sides. */
const MIDDLE_DOT = /\s(?:·|\\u00b7|&middot;|&#183;)\s/gi;

const noMiddleDotMeta = defineRule({
  lifecycle: 'state',
  standard: {
    id: 'copy/no-middle-dot-meta',
    revision: 1,
    title: 'No meta strings joined with middle dots',
    guidance: {
      standard:
        'Metadata is laid out with line breaks, columns or hairlines, never joined into one string with middle dots (A · B · C).',
      checks: [
        'One dot in a byline, a caption or a live state is fine; that shape is not reported.',
        "A marquee's repeating separator is the one legal join: accept with that reason.",
      ],
      examples: [
        { label: 'Separate cells', code: '<dl><dt>Role</dt><dd>{role}</dd><dt>Year</dt><dd>{year}</dd></dl>' },
      ],
    },
  },
  detector: {
    id: 'ts/middle-dot-join',
    version: 1,
    scan: 'file',
    createOnce({ context }) {
      const joined = (node: AgentlintNode) => {
        if ((node.text.match(MIDDLE_DOT) ?? []).length >= 2)
          context.report({
            node,
            message: 'Meta string joined with middle dots: use line breaks, columns or hairlines.',
          });
      };
      return {
        string: joined,
        template_string: joined,
        // JSX splits text around entities, so the element's own text pieces are read together.
        jsx_element(node: AgentlintNode) {
          const own = node.children.filter(
            (child) => child.type === 'jsx_text' || child.type === 'html_character_reference',
          );
          if (
            (
              own
                .map((child) => child.text)
                .join('')
                .match(MIDDLE_DOT) ?? []
            ).length >= 2
          )
            context.report({
              node,
              message: 'Meta string joined with middle dots: use line breaks, columns or hairlines.',
            });
        },
        call_expression(node: AgentlintNode) {
          const callee = node.childByFieldName('function');
          const args = node.childByFieldName('arguments');
          if (callee?.type !== 'member_expression' || !callee.text.endsWith('.join') || !args) return;
          if (/^\(\s*(['"`])\s*(?:·|\\u00b7|&middot;)\s*\1\s*\)$/i.test(args.text))
            context.report({ node, message: 'Meta joined with middle dots: use line breaks, columns or hairlines.' });
        },
      };
    },
    fixtures: {
      mustReport: [
        "const meta = [kind, year, role].join(' · ');",
        'const meta = `${kind} · ${year} · ${role}`;',
        "const meta = 'Design \\u00b7 Build \\u00b7 Ship';",
        { file: 'fixture.tsx', source: 'const m = <p>Design &middot; Build &middot; Ship</p>;' },
      ],
      mustStaySilent: [
        'const live = `Last played · ${when}`;',
        "const title = 'Samuel Mussie · Software Engineer';",
        "const list = items.join(', ');",
      ],
    },
  },
  binding: {
    id: 'copy/no-middle-dot-meta',
    authority: 'agent',
    include: ['src/**/*.{ts,tsx,js,mjs}'],
  },
});

export default defineConfig({
  rules: [noEmDash, noSecondaryText, noMiddleDotMeta],
  ignores: ['dist/**', '.astro/**', 'coverage/**'],
});
